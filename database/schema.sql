-- RUANG AKSARA - Skema PostgreSQL
-- Jalankan di pgAdmin (Query Tool) pada database kosong "ruang_aksara", atau:
--   psql -U postgres -d ruang_aksara -f database/schema.sql

DROP TABLE IF EXISTS reviews, fines, loans, announcements, book_covers, books, categories, users CASCADE;

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_lengkap VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE CHECK (email = lower(email)),
  password_hash TEXT NOT NULL,
  nomor_identitas VARCHAR(30) NOT NULL UNIQUE,
  role VARCHAR(20) NOT NULL CHECK (role IN ('admin','pegawai','mahasiswa')),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_kategori VARCHAR(100) NOT NULL UNIQUE,
  kode_klasifikasi VARCHAR(20) NOT NULL UNIQUE,
  deskripsi TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE books (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
  isbn VARCHAR(20) NOT NULL UNIQUE,
  judul VARCHAR(200) NOT NULL,
  pengarang VARCHAR(150) NOT NULL,
  penerbit VARCHAR(150) NOT NULL,
  tahun_terbit SMALLINT NOT NULL CHECK (tahun_terbit BETWEEN 1000 AND 2100),
  stok_total INTEGER NOT NULL CHECK (stok_total >= 0),
  stok_tersedia INTEGER NOT NULL CHECK (stok_tersedia >= 0),
  durasi_maks_pinjam SMALLINT NOT NULL CHECK (durasi_maks_pinjam > 0),
  denda_per_hari NUMERIC(12,2) NOT NULL CHECK (denda_per_hari >= 0),
  sampul TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (stok_tersedia <= stok_total)
);

-- Gambar sampul yang diunggah manual (maks 5 MB, divalidasi di Server Action)
CREATE TABLE book_covers (
  book_id BIGINT PRIMARY KEY REFERENCES books(id) ON DELETE CASCADE,
  mime_type VARCHAR(50) NOT NULL CHECK (mime_type IN ('image/jpeg','image/png','image/webp','image/gif')),
  data BYTEA NOT NULL CHECK (octet_length(data) <= 5242880),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE announcements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  judul VARCHAR(200) NOT NULL,
  konten TEXT NOT NULL,
  kategori VARCHAR(20) NOT NULL CHECK (kategori IN ('operasional','layanan','acara')),
  tanggal_rilis DATE NOT NULL DEFAULT CURRENT_DATE,
  status VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published')),
  created_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE loans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_pinjam VARCHAR(30) NOT NULL UNIQUE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
  status VARCHAR(30) NOT NULL DEFAULT 'menunggu_konfirmasi'
    CHECK (status IN ('menunggu_konfirmasi','sedang_dipinjam','selesai','ditolak')),
  alasan_penolakan TEXT,
  tanggal_pengajuan TIMESTAMPTZ NOT NULL DEFAULT now(),
  tanggal_pinjam TIMESTAMPTZ,
  jatuh_tempo DATE,
  tanggal_kembali TIMESTAMPTZ,
  status_perpanjangan VARCHAR(30) NOT NULL DEFAULT 'tidak_ada'
    CHECK (status_perpanjangan IN ('tidak_ada','perpanjangan_diajukan','perpanjangan_disetujui','perpanjangan_ditolak')),
  jumlah_perpanjangan SMALLINT NOT NULL DEFAULT 0 CHECK (jumlah_perpanjangan BETWEEN 0 AND 1),
  approved_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  returned_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (status <> 'ditolak' OR alasan_penolakan IS NOT NULL)
);
-- Satu mahasiswa tidak boleh punya dua pinjaman aktif untuk buku yang sama
CREATE UNIQUE INDEX uq_loan_aktif ON loans(user_id, book_id)
  WHERE status IN ('menunggu_konfirmasi','sedang_dipinjam');

CREATE TABLE fines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_id BIGINT NOT NULL UNIQUE REFERENCES loans(id) ON DELETE RESTRICT,
  hari_terlambat INTEGER NOT NULL CHECK (hari_terlambat >= 0),
  tarif_per_hari NUMERIC(12,2) NOT NULL,           -- snapshot dari books.denda_per_hari
  jumlah_denda NUMERIC(12,2) NOT NULL CHECK (jumlah_denda >= 0),
  status VARCHAR(20) NOT NULL DEFAULT 'tertunggak' CHECK (status IN ('tertunggak','lunas')),
  dicatat_oleh BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  dibayar_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_id BIGINT NOT NULL UNIQUE REFERENCES loans(id) ON DELETE RESTRICT,
  book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  komentar TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_books_category ON books(category_id);
CREATE INDEX idx_loans_user ON loans(user_id);
CREATE INDEX idx_loans_book ON loans(book_id);
CREATE INDEX idx_loans_status ON loans(status);
CREATE INDEX idx_fines_status ON fines(status);
CREATE INDEX idx_reviews_book ON reviews(book_id);
CREATE INDEX idx_ann_status ON announcements(status, tanggal_rilis);
